//#################################################################################################

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *uart_handle)
{
    if (uart_handle->Instance == USART1)
    {
        gnss_uart_reader_handle_byte(get_gnss_uart_reader());
    }
}

