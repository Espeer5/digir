__attribute__((noreturn))                                                                           
void fatal_err()                                                                                    
{                                                                                                   
    __disable_irq();                                                                                
                                                                                                    
#ifdef DEBUG                                                                                        
                                                                                                    
    __BKPT(0);                                                                                      
                                                                                                    
    while (1)                                                                                       
    {                                                                                               
        __NOP();                                                                                    
    }                                                                                               
                                                                                                    
#else                                                                                               
                                                                                                    
    NVIC_SystemReset();                                                                             
                                                                                                    
    while (1) {}                                                                                    
                                                                                                    
#endif // #ifdef DEBUG                                                                              
}

